shortlist = filtered[:5]

print(f"Shortlist: {len(shortlist)} jobs")

# Same as n8n's Basic LLM Chain — one model call per item
CANDIDATE = """Based in Nigeria, needs fully remote work.
Can write Python, do basic data analysis, and build small AI applications using APIs.
No commercial experience yet."""

